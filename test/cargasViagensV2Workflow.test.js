import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import request from 'supertest';
import {pool} from '../src/db/pool.js';
import {clientPool} from '../src/db/clientPool.js';
import {tableName} from '../src/config.js';
import {cargasViagensV2Router} from '../src/routes/cargasViagensV2.js';

// The complete write workflow runs only against session-local temporary tables.
test('real SQL: document before trip, trip edit, removal, conflict and rollback', {
  skip: process.env.CARGAS_WORKFLOW_DB_TEST !== '1',
}, async t => {
  const db = await pool.connect();
  const names = ['cargas_v2','viagens_v2','viagem_cargas_v2','carga_rotas_v2','carga_documentos_v2'];
  try {
    await db.query('BEGIN');
    for (const name of names) {
      await db.query(`CREATE TEMP TABLE ${name} (LIKE ${tableName(name)} INCLUDING DEFAULTS INCLUDING INDEXES) ON COMMIT DROP`);
      const columns = await db.query(`SELECT attname FROM pg_attribute WHERE attrelid=$1::regclass AND attname='id'`, [`pg_temp.${name}`]);
      if (columns.rowCount) {
        await db.query(`ALTER TABLE pg_temp.${name} ALTER COLUMN id DROP DEFAULT`);
        await db.query(`ALTER TABLE pg_temp.${name} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
      }
    }
    await db.query('ALTER TABLE pg_temp.viagem_cargas_v2 ADD FOREIGN KEY (viagem_id) REFERENCES pg_temp.viagens_v2(id) ON DELETE CASCADE, ADD FOREIGN KEY (carga_id) REFERENCES pg_temp.cargas_v2(id) ON DELETE CASCADE');
    await db.query('ALTER TABLE pg_temp.carga_documentos_v2 ADD FOREIGN KEY (carga_id) REFERENCES pg_temp.cargas_v2(id) ON DELETE CASCADE');
    await db.query('ALTER TABLE pg_temp.carga_rotas_v2 ADD FOREIGN KEY (carga_id) REFERENCES pg_temp.cargas_v2(id) ON DELETE CASCADE');
    const query = async (sql, args) => {
      if (sql === 'BEGIN') return db.query('SAVEPOINT route_write');
      if (sql === 'COMMIT') return db.query('RELEASE SAVEPOINT route_write');
      if (sql === 'ROLLBACK') return db.query('ROLLBACK TO SAVEPOINT route_write');
      for (const name of names) {
        sql = sql.replaceAll(tableName(name), `pg_temp.${name}`)
          .replaceAll(tableName(name).replaceAll('"',''), `pg_temp.${name}`);
      }
      return db.query(sql, args);
    };
    t.mock.method(pool, 'connect', async () => ({query, release(){}}));
    t.mock.method(pool, 'query', query);
    t.mock.method(clientPool, 'query', async () => ({rows:[]}));
    const app=express(); app.use(express.json()); app.use(cargasViagensV2Router);
    app.use((err,_req,res,_next)=>res.status(500).json({error:err.message}));
    const create=await request(app).post('/cargas-viagens-v2/cargas').send({cliente:'QA isolated'});
    assert.equal(create.status,201,JSON.stringify(create.body));
    const id=create.body.id;
    const editLoad=await request(app).put(`/cargas-viagens-v2/cargas/${id}`).send({cliente:'QA edited',origem:'Origem',destino:'Destino',valorCliente:1234,peso:500,paradas:[{tipo:'entrega',cidade:'Parada',uf:'SC',nf:'10'}]});
    assert.equal(editLoad.status,200,JSON.stringify(editLoad.body));
    assert.equal(editLoad.body.valorCliente,1234);
    assert.equal(editLoad.body.paradas[0].cidade,'Parada');
    const url=`/cargas-viagens-v2/cargas/${id}/documentos`;
    const documentos=[{tipo:'Orçamento',numero:'1283',empresa:'2',serie:'O'},{tipo:'CT-e',numero:'1283',empresa:'2',serie:'1'}];
    const link=await request(app).put(url).send({documentos});
    assert.equal(link.status,200,JSON.stringify(link.body));
    assert.equal(link.body.status,'aguardando_viagem');
    assert.equal(link.body.documentos.length,2);
    // Reproduce the screenshot: a legacy number-only CT-e and a fully identified budget.
    const legacy={tipo:'CT-e',numero:'1283',observacoes:'ERP - CT-e O-1283'};
    await request(app).put(url).send({documentos:[legacy,documentos[0]]}).expect(200);
    const removeLegacy=await request(app).put(url).send({documentos:[documentos[0]]});
    assert.equal(removeLegacy.body.documentos.length,1);
    assert.equal(removeLegacy.body.documentos[0].tipo,'Orçamento');
    assert.equal(removeLegacy.body.documentos[0].serie,'O');
    const persisted=await request(app).get(`/cargas-viagens-v2/cargas/${id}`);
    assert.equal(persisted.body.documentos.length,1);
    assert.equal(persisted.body.documentos[0].empresa,'2');
    await request(app).put(url).send({documentos}).expect(200);
    await request(app).put(url).send({}).expect(400);
    await request(app).put(url).send({documentos:[null]}).expect(400);
    assert.equal((await db.query('SELECT COUNT(*)::int AS total FROM pg_temp.carga_documentos_v2')).rows[0].total,2);
    const trip=await request(app).post('/cargas-viagens-v2/viagens').send({placa:'QA00000',cargaIds:[id]});
    assert.equal(trip.status,201,JSON.stringify(trip.body));
    assert.equal(trip.body.cargas[0].status,'em_transito');
    assert.equal(trip.body.situacao,'em_transito');
    await request(app).delete(`/cargas-viagens-v2/cargas/${id}`).expect(409);
    const linked=await request(app).get('/cargas-viagens-v2/cargas').query({status:'veiculo_vinculado',page:1,pageSize:25});
    assert.equal(linked.status,200,JSON.stringify(linked.body));
    assert.equal(linked.body.total,1);
    assert.equal(linked.body.items[0].id,id);
    const tripUrl=`/cargas-viagens-v2/viagens/${trip.body.id}`;
    const second=await request(app).post('/cargas-viagens-v2/cargas').send({cliente:'Segunda carga QA'});
    assert.equal(second.status,201);
    const addLoad=await request(app).put(tripUrl).send({placa:'QA00000',cargaIds:[id,second.body.id]});
    assert.equal(addLoad.status,200,JSON.stringify(addLoad.body));
    assert.equal(addLoad.body.cargas.length,2);
    assert.equal(addLoad.body.cargas.find(c=>c.id===id).documentos.length,2);
    const detachLoad=await request(app).put(tripUrl).send({placa:'QA00000',cargaIds:[id]});
    assert.equal(detachLoad.status,200);
    assert.equal((await request(app).get(`/cargas-viagens-v2/cargas/${second.body.id}`)).body.status,'aguardando_viagem');
    await request(app).delete(`/cargas-viagens-v2/cargas/${second.body.id}`).expect(204);
    const financialFilter=await request(app).get('/cargas-viagens-v2/cargas').query({financeiro:'revisar',q:'QA edited',page:1,pageSize:25});
    assert.equal(financialFilter.status,200,JSON.stringify(financialFilter.body));
    assert.equal(financialFilter.body.total,1);
    await request(app).post('/cargas-viagens-v2/viagens').send({cargaIds:[id]}).expect(409);
    const removed=await request(app).put(url).send({documentos:[]});
    assert.equal(removed.body.status,'aguardando_cte');
    await request(app).put(url).send({documentos}).expect(200);
    await db.query("UPDATE pg_temp.cargas_v2 SET status='entregue' WHERE id=$1",[id]);
    const edited=await request(app).put(tripUrl).send({placa:'QA00000',cargaIds:[id]});
    assert.equal(edited.status,200,JSON.stringify(edited.body));
    assert.equal(edited.body.cargas[0].status,'entregue');
    assert.equal(edited.body.situacao,'entregue');
    await request(app).put('/cargas-viagens-v2/cargas/99999/documentos').send({documentos:[]}).expect(404);
    assert.equal((await db.query('SELECT COUNT(*)::int AS total FROM pg_temp.carga_documentos_v2')).rows[0].total,2);
    await request(app).delete(tripUrl).expect(204);
    assert.equal((await db.query('SELECT status FROM pg_temp.cargas_v2 WHERE id=$1',[id])).rows[0].status,'entregue');
    assert.equal((await db.query('SELECT COUNT(*)::int AS total FROM pg_temp.viagem_cargas_v2')).rows[0].total,0);
    await request(app).delete(`/cargas-viagens-v2/cargas/${id}`).expect(204);
    await request(app).get(`/cargas-viagens-v2/cargas/${id}`).expect(404);
    assert.equal((await db.query('SELECT COUNT(*)::int AS total FROM pg_temp.carga_documentos_v2')).rows[0].total,0);
    assert.equal((await db.query('SELECT COUNT(*)::int AS total FROM pg_temp.carga_rotas_v2')).rows[0].total,0);
  } finally {
    await db.query('ROLLBACK'); db.release();
    t.mock.restoreAll(); await pool.end(); await clientPool.end();
  }
});
