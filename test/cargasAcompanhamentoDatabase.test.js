import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import request from 'supertest';
import {pool} from '../src/db/pool.js';
import {clientPool} from '../src/db/clientPool.js';
import {tableName} from '../src/config.js';
import {cargasViagensV2Router} from '../src/routes/cargasViagensV2.js';

test('SQL real isolado: previsoes, conflitos, nao carregamento, reabertura e alertas', {skip:process.env.CARGAS_WORKFLOW_DB_TEST!=='1'},async t=>{
  const db = await pool.connect();
  const names = ['cargas_v2','viagens_v2','viagem_cargas_v2','carga_rotas_v2','carga_documentos_v2'];
  try {
    await db.query('BEGIN');
    for (const name of names) {
      await db.query(`CREATE TEMP TABLE ${name} (LIKE ${tableName(name)} INCLUDING DEFAULTS INCLUDING INDEXES) ON COMMIT DROP`);
      const columns = await db.query(`SELECT attname FROM pg_attribute WHERE attrelid=$1::regclass AND attname='id'`, [`pg_temp.${name}`]);
      if (columns.rowCount) {
        await db.query(`ALTER TABLE pg_temp.${name} ALTER COLUMN id DROP DEFAULT`);
        await db.query(`ALTER TABLE pg_temp.${name} ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`);
      }
    }
    await db.query('ALTER TABLE pg_temp.viagem_cargas_v2 ADD FOREIGN KEY (viagem_id) REFERENCES pg_temp.viagens_v2(id) ON DELETE CASCADE, ADD FOREIGN KEY (carga_id) REFERENCES pg_temp.cargas_v2(id) ON DELETE CASCADE');
    await db.query('ALTER TABLE pg_temp.carga_documentos_v2 ADD FOREIGN KEY (carga_id) REFERENCES pg_temp.cargas_v2(id) ON DELETE CASCADE');
    await db.query('ALTER TABLE pg_temp.carga_rotas_v2 ADD FOREIGN KEY (carga_id) REFERENCES pg_temp.cargas_v2(id) ON DELETE CASCADE');
    const query = async (sql, args) => {
      if (sql === 'BEGIN') return db.query('SAVEPOINT route_write');
      if (sql === 'COMMIT') return db.query('RELEASE SAVEPOINT route_write');
      if (sql === 'ROLLBACK') return db.query('ROLLBACK TO SAVEPOINT route_write');
      for (const name of names) {
        sql = sql.replaceAll(tableName(name), `pg_temp.${name}`)
          .replaceAll(tableName(name).replaceAll('"',''), `pg_temp.${name}`);
      }
      return db.query(sql, args);
    };
    t.mock.method(pool, 'connect', async () => ({query, release(){}}));
    t.mock.method(pool, 'query', query);
    t.mock.method(clientPool, 'query', async (sql,args) => ({rows:sql.includes('financeiro.responsaveis') && args?.[0]==='1' ? [{codigo:'1',empresa:'1',nome:'Responsavel ERP'}] : []}));
    const app=express(); app.use(express.json()); app.use(cargasViagensV2Router);
    app.use((err,_req,res,_next)=>res.status(err.statusCode || 500).json({error:err.message}));

    const base={cliente:'QA previsao',responsavel:{codigo:'1',empresa:'1'},previsao:'2026-11-24T10:00'};
    const created=await request(app).post('/cargas-viagens-v2/cargas').send(base).expect(201);
    const id=created.body.id,url=`/cargas-viagens-v2/cargas/${id}`;
    assert.equal(created.body.previsao,base.previsao);
    await request(app).put(url).send({...base,previsao:'2026-11-25T10:00'}).expect(400);
    assert.equal((await request(app).get(url)).body.previsao,base.previsao);
    await request(app).put(url).send({...base,previsao:'2026-11-25T10:00',previsaoAnterior:base.previsao,motivoPrevisao:'Cliente reagendou'}).expect(200);
    await request(app).put(url).send({...base,previsao:'2026-11-26T10:00',previsaoAnterior:base.previsao,motivoPrevisao:'Conflito teste'}).expect(409);
    await request(app).post(`${url}/nao-carregada`).send({motivo:'Outro'}).expect(400);
    await db.query("INSERT INTO pg_temp.carga_documentos_v2(carga_id,tipo_documento,numero_documento) VALUES($1,'CT-e','QA')",[id]);
    await request(app).post(`${url}/nao-carregada`).send({motivo:'Cliente desistiu'}).expect(409);
    await db.query('DELETE FROM pg_temp.carga_documentos_v2 WHERE carga_id=$1',[id]);
    await request(app).post(`${url}/nao-carregada`).send({motivo:'Cliente desistiu',observacoes:'Teste isolado'}).expect(200);
    const closed=(await request(app).get(url)).body;
    assert.equal(closed.status,'nao_carregada');assert.equal(closed.alerta,null);
    assert.equal(closed.acompanhamento.historico.length,3);
    await request(app).delete(url).expect(409);
    await request(app).post('/cargas-viagens-v2/viagens').send({cargaIds:[id]}).expect(409);
    await request(app).put(`${url}/documentos`).send({documentos:[]}).expect(409);
    const report=await request(app).get('/cargas-viagens-v2/nao-carregadas').expect(200);
    assert.equal(report.body.length,1);assert.equal(report.body[0].acompanhamento.naoCarregada.motivo,'Cliente desistiu');
    await request(app).post(`${url}/nao-carregada`).send({reabrir:true,motivo:'Cliente retomou'}).expect(200);
    assert.equal((await request(app).get(url)).body.acompanhamento.historico.length,4);
    assert.equal((await request(app).get('/cargas-viagens-v2/nao-carregadas')).body.length,0);
    const trip=await request(app).post('/cargas-viagens-v2/viagens').send({cargaIds:[id],previsao:'2026-11-26T18:00'}).expect(201);
    assert.equal(trip.body.previsao,'2026-11-26T18:00');
    const tripUrl=`/cargas-viagens-v2/viagens/${trip.body.id}`;
    await request(app).put(tripUrl).send({cargaIds:[id],previsaoCarregamento:'2026-11-25T08:00'}).expect(200);
    assert.equal((await request(app).get(tripUrl)).body.previsaoCarregamento,'2026-11-25T08:00');
    await request(app).put(tripUrl).send({cargaIds:[id],previsaoCarregamento:'2026-11-28T08:00',motivoCarregamento:'Teste de cronologia'}).expect(400);
    assert.equal((await request(app).get(tripUrl)).body.previsaoCarregamento,'2026-11-25T08:00');

    await request(app).post(`${url}/nao-carregada`).send({motivo:'Cliente desistiu'}).expect(409);
    await request(app).put(`/cargas-viagens-v2/viagens/${trip.body.id}`).send({cargaIds:[id],previsao:'2026-11-27T18:00'}).expect(400);
    await request(app).put(`/cargas-viagens-v2/viagens/${trip.body.id}`).send({cargaIds:[id],previsao:'2026-11-27T18:00',motivoPrevisao:'Atraso na entrega'}).expect(200);
    // SQL counters and predicates use the database clock and all rows, not just a page.
    await db.query(`UPDATE pg_temp.cargas_v2 SET acompanhamento=jsonb_set(acompanhamento,'{previsao}',to_jsonb(to_char((now() AT TIME ZONE 'America/Sao_Paulo')-interval '1 day','YYYY-MM-DD"T"HH24:MI')))`);
    await db.query(`UPDATE pg_temp.viagens_v2 SET acompanhamento=jsonb_set(acompanhamento,'{previsao}',to_jsonb(to_char((now() AT TIME ZONE 'America/Sao_Paulo')+interval '1 day','YYYY-MM-DD"T"HH24:MI')))`);
    const stats=await request(app).get('/cargas-viagens-v2/alertas').expect(200);
    assert.equal(stats.body.carga.vencida,1);assert.equal(stats.body.viagem.amanha,1);
    const {forecastFilter}=await import('../src/services/cargasAcompanhamento.js');
    assert.equal((await db.query(`SELECT id FROM pg_temp.cargas_v2 c WHERE ${forecastFilter('carga','vencida')}`)).rowCount,1);
    assert.equal((await db.query(`SELECT id FROM pg_temp.cargas_v2 c WHERE ${forecastFilter('carga','hoje')}`)).rowCount,0);
    await request(app).post('/cargas-viagens-v2/cargas').send({...base,previsao:'2026-02-30T10:00'}).expect(400);
    assert.equal((await db.query('SELECT * FROM pg_temp.cargas_v2')).rowCount,1);
  } finally {await db.query('ROLLBACK');db.release();await pool.end();await clientPool.end();}
});
